from pydantic import BaseModel, Field
from typing import List, Optional

class ResumeScoreSchema(BaseModel):
    score: int = Field(..., description="Overall fit score from 1 to 100")
    matching_skills: List[str] = Field(..., description="List of skills the candidate has that match the job description")
    missing_skills: List[str] = Field(..., description="List of important skills missing from the resume")
    strengths: List[str] = Field(..., description="Key strengths identified in the resume")
    weaknesses: List[str] = Field(..., description="Key weaknesses or areas of concern")
    summary: str = Field(..., description="A 2-3 sentence summary of the candidate's fit for the role")

class CandidateJobMatchSchema(BaseModel):
    match_percentage: int = Field(..., description="Match percentage from 0 to 100")
    rationale: str = Field(..., description="Detailed explanation of why this percentage was assigned")

class SkillGapAnalysisSchema(BaseModel):
    current_skills: List[str] = Field(..., description="Skills the candidate currently possesses")
    required_skills: List[str] = Field(..., description="Skills required by the job")
    gap_skills: List[str] = Field(..., description="Skills the candidate needs to learn")
    recommendation: str = Field(..., description="Advice on how to bridge the skill gap")

class InterviewQuestionItem(BaseModel):
    question: str = Field(..., description="The interview question text")
    model_answer: str = Field(..., description="A concise model/reference answer for the recruiter")
    difficulty: str = Field(..., description="Easy, Medium, or Hard")


class InterviewQuestionCategory(BaseModel):
    name: str = Field(..., description="Category name: Technical, Resume-Based, Scenario, Problem-Solving, Behavioral, or HR")
    questions: List[InterviewQuestionItem] = Field(..., description="List of questions in this category")


class InterviewQuestionSetSchema(BaseModel):
    """Structured multi-category interview question set generated by Groq."""
    categories: List[InterviewQuestionCategory] = Field(
        ...,
        description="List of question categories, each with a name and a list of questions."
    )


# Keep old name as alias for any legacy code
InterviewQuestionGenSchema = InterviewQuestionSetSchema

class InterviewSummarySchema(BaseModel):
    summary: str = Field(..., description="A comprehensive 3-4 sentence summary of the interview performance.")
    strengths: List[str] = Field(..., description="Key strengths demonstrated during the interview.")
    weaknesses: List[str] = Field(..., description="Areas for improvement or weaknesses identified.")
    communication_score: int = Field(..., description="Score from 1-100 evaluating communication skills.")
    technical_score: int = Field(..., description="Score from 1-100 evaluating technical proficiency.")
    confidence_score: int = Field(..., description="Score from 1-100 evaluating confidence and presence.")
    hiring_recommendation: str = Field(..., description="Final recommendation: 'Hire', 'Strong Hire', 'No Hire', or 'Hold'.")
    next_round_suggestion: str = Field(..., description="Suggestion for the focus of the next interview round, if applicable.")

class JobOptimizationSchema(BaseModel):
    optimized_title: str = Field(..., description="An optimized, catchy job title")
    optimized_description: str = Field(..., description="The rewritten, highly engaging job description")
    suggested_skills: List[str] = Field(..., description="List of suggested keywords or skills to include")


class CandidateRankingEvalSchema(BaseModel):
    """
    Groq's structured evaluation of a candidate against a job — Phase 07.
    This produces the ai_evaluation_score (0-100) and explanations.
    The backend deterministic engine assigns the final overall_score.
    """
    ai_score: int = Field(
        ...,
        description="Your qualitative assessment of candidate-job fit, from 0 to 100. "
                    "Do NOT base this on protected attributes (age, gender, race, religion, etc). "
                    "Focus only on professional skills, experience, education, and relevant certifications."
    )
    strengths: List[str] = Field(..., description="List of 2-4 key strengths the candidate brings to this role.")
    missing_skills: List[str] = Field(..., description="List of important skills or experience absent from the resume.")
    concerns: List[str] = Field(default_factory=list, description="Any professional concerns or risks (optional).")
    rationale: str = Field(..., description="2-3 sentence reasoning for the ai_score. Must not reference protected personal attributes.")


class InterviewIntelligenceSchema(BaseModel):
    """
    Groq's structured analysis of an interview transcript — Module 7.
    This is decision SUPPORT only. Recruiter makes the final call.
    """
    summary: str = Field(..., description="3-4 sentence overall interview performance summary.")
    technical_knowledge: str = Field(..., description="Assessment of the candidate's technical knowledge demonstrated.")
    problem_solving: str = Field(..., description="Assessment of problem-solving approach and quality.")
    communication: str = Field(..., description="Assessment of communication clarity and effectiveness.")
    strengths: List[str] = Field(..., description="Key strengths demonstrated during the interview (2-5 items).")
    weaknesses: List[str] = Field(..., description="Areas for improvement or weaknesses observed (1-4 items).")
    relevant_answers: List[str] = Field(default_factory=list, description="Notable relevant answers the candidate gave.")
    areas_of_concern: List[str] = Field(default_factory=list, description="Professional concerns or gaps identified (not personal attributes).")
    overall_evaluation: str = Field(..., description="1-2 sentence overall evaluation.")
    communication_score: int = Field(..., description="Score 0-100 for communication skills.")
    technical_score: int = Field(..., description="Score 0-100 for technical proficiency.")
    confidence_score: int = Field(..., description="Score 0-100 for confidence and presence.")
    problem_solving_score: int = Field(..., description="Score 0-100 for problem-solving ability.")
    hiring_recommendation: str = Field(
        ...,
        description="Recommendation: 'Strong Hire', 'Hire', 'Hold', or 'No Hire'. "
                    "This is DECISION SUPPORT — recruiter makes the final call."
    )
    next_round_suggestion: str = Field(..., description="Focus area suggestion for the next interview round, if applicable.")
